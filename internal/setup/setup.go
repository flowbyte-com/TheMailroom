// Package setup implements TheMailroom's first-run configuration
// experience.
//
// It asks a short series of questions, renders a configuration that the
// existing loader accepts, validates it with that same loader, and writes
// it with a no-overwrite, owner-only strategy. It never asks for or stores
// a plaintext password: the operator names a credential command, and the
// command is reported by its executable name only.
//
// Nothing in this package opens a network connection, runs a credential
// command or starts the server.
package setup

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"

	"gopkg.in/yaml.v3"

	"github.com/flowbyte-com/themailroom/internal/config"
)

// Answers is the configuration the operator asked for.
type Answers struct {
	// AccountID is the stable account identifier exposed to MCP tools.
	AccountID string
	// Email is the account's address.
	Email string

	// IMAPHost is the IMAP server name.
	IMAPHost string
	// IMAPPort is the IMAP port.
	IMAPPort int
	// IMAPImplicitTLS selects implicit TLS. When false, mandatory
	// STARTTLS is used. There is no plaintext mode.
	IMAPImplicitTLS bool
	// IMAPUsername is the IMAP login name.
	IMAPUsername string
	// IMAPCommand is the credential command, as an argument vector.
	IMAPCommand []string

	// EnableSend grants the send capability and writes the SMTP block. It
	// is false unless the operator explicitly opts in.
	EnableSend bool
	// SMTPHost is the submission server name.
	SMTPHost string
	// SMTPPort is the submission port.
	SMTPPort int
	// SMTPImplicitTLS selects implicit TLS. When false, mandatory
	// STARTTLS is used.
	SMTPImplicitTLS bool
	// SMTPUsername is the SMTP login name.
	SMTPUsername string
	// SMTPCommand is the credential command, as an argument vector.
	SMTPCommand []string
}

// header is the fixed comment block written above the configuration.
//
// It is a constant, so no operator input can affect it.
const header = `# TheMailroom configuration
#
# Generated by "themailroom setup". Review it before use.
#
# No password is stored here: each credential is read from the command in
# password_command. The command is executed directly, never through a
# shell, with bounded output and a bounded timeout.
#
# Validate this file with:
#   themailroom doctor -config <path>
# Test connectivity, which runs the credential command, with:
#   themailroom doctor -config <path> -network
`

// document mirrors the configuration schema that setup writes.
//
// It is a separate type rather than config.Config so the generated file
// contains exactly the fields setup intends and nothing else. The result
// is still validated by the real loader, so the two cannot drift.
type document struct {
	Server   serverDocument    `yaml:"server"`
	Accounts []accountDocument `yaml:"accounts"`
}

type serverDocument struct {
	LogLevel string `yaml:"log_level"`
}

type accountDocument struct {
	ID          string        `yaml:"id"`
	Backend     string        `yaml:"backend"`
	Email       string        `yaml:"email"`
	Permissions []string      `yaml:"permissions"`
	IMAP        imapDocument  `yaml:"imap"`
	SMTP        *smtpDocument `yaml:"smtp,omitempty"`
}

type imapDocument struct {
	Host            string   `yaml:"host"`
	Port            int      `yaml:"port"`
	TLS             bool     `yaml:"tls,omitempty"`
	StartTLS        bool     `yaml:"starttls,omitempty"`
	Username        string   `yaml:"username"`
	PasswordCommand []string `yaml:"password_command"`
}

type smtpDocument struct {
	Host            string   `yaml:"host"`
	Port            int      `yaml:"port"`
	TLS             bool     `yaml:"tls,omitempty"`
	StartTLS        bool     `yaml:"starttls,omitempty"`
	Username        string   `yaml:"username"`
	PasswordCommand []string `yaml:"password_command"`
}

// Generate renders the configuration for the answers and validates it with
// the loader the server uses.
//
// The returned bytes are exactly what was validated, so what is written is
// what was checked. Nothing is written by this function.
func Generate(a Answers) ([]byte, config.Config, error) {
	permissions := []string{"read"}
	if a.EnableSend {
		// Sending is granted only when the operator opted in. Attachment
		// sending is never granted by setup.
		permissions = append(permissions, "send")
	}

	imap := imapDocument{
		Host:            a.IMAPHost,
		Port:            a.IMAPPort,
		Username:        a.IMAPUsername,
		PasswordCommand: append([]string(nil), a.IMAPCommand...),
	}
	if a.IMAPImplicitTLS {
		imap.TLS = true
	} else {
		imap.StartTLS = true
	}

	account := accountDocument{
		ID:          a.AccountID,
		Backend:     "imap",
		Email:       a.Email,
		Permissions: permissions,
		IMAP:        imap,
	}
	if a.EnableSend {
		smtp := &smtpDocument{
			Host:            a.SMTPHost,
			Port:            a.SMTPPort,
			Username:        a.SMTPUsername,
			PasswordCommand: append([]string(nil), a.SMTPCommand...),
		}
		if a.SMTPImplicitTLS {
			smtp.TLS = true
		} else {
			smtp.StartTLS = true
		}
		account.SMTP = smtp
	}

	doc := document{
		Server:   serverDocument{LogLevel: config.DefaultLogLevel},
		Accounts: []accountDocument{account},
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	// Match the two-space style used by the documentation and the examples.
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, config.Config{}, fmt.Errorf("setup: render configuration: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, config.Config{}, fmt.Errorf("setup: render configuration: %w", err)
	}
	data := buf.Bytes()

	cfg, err := config.Parse(data)
	if err != nil {
		// The loader's message can embed the values that were entered, so
		// only a fixed description is reported here.
		return nil, config.Config{}, errors.New(
			"setup: the values entered do not form a valid configuration; nothing was written. " +
				"Check the account id, email address, hosts, ports and credential commands, then run setup again")
	}
	return data, cfg, nil
}

// Options configures a setup run.
type Options struct {
	// Path is the destination configuration file.
	Path string
	// Force allows an existing regular file to be replaced.
	Force bool
	// In and Out are the prompt streams. Nil selects the process streams.
	In  io.Reader
	Out io.Writer
	// Check, when set, is offered as an explicit post-setup connectivity
	// check. It is invoked only if the operator answers yes.
	Check func(ctx context.Context, path string, out io.Writer) error
}

// Run performs the interactive setup.
//
// The configuration is validated before it is written, and an existing
// file is never replaced unless Force is set. Nothing touches the network
// or executes a credential command unless the operator explicitly opts
// into the final connectivity check.
func Run(ctx context.Context, opts Options) error {
	in := opts.In
	if in == nil {
		in = os.Stdin
	}
	out := opts.Out
	if out == nil {
		out = os.Stdout
	}
	p := newPrompter(in, out)

	fmt.Fprintln(out, "TheMailroom setup")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "This writes a new configuration file. It does not ask for or store a")
	fmt.Fprintln(out, "plaintext password: it records a credential command instead, which is")
	fmt.Fprintln(out, "run only when the server or a network diagnostic needs the secret.")
	fmt.Fprintln(out)

	var a Answers

	var err error
	if a.AccountID, err = p.ask(ctx, "Account id", "personal", true); err != nil {
		return err
	}
	if a.Email, err = p.ask(ctx, "Email address", "", true); err != nil {
		return err
	}

	fmt.Fprintln(out)
	fmt.Fprintln(out, "Incoming mail (IMAP), always over verified TLS")
	if a.IMAPHost, err = p.ask(ctx, "  IMAP host", "", true); err != nil {
		return err
	}
	mode, err := p.askChoice(ctx, "  IMAP TLS mode", []string{"implicit TLS", "STARTTLS"}, 1)
	if err != nil {
		return err
	}
	a.IMAPImplicitTLS = mode == 0
	defaultPort := config.DefaultIMAPPort
	if !a.IMAPImplicitTLS {
		defaultPort = config.DefaultIMAPPortStartTLS
	}
	if a.IMAPPort, err = p.askPort(ctx, "  IMAP port", defaultPort); err != nil {
		return err
	}
	if a.IMAPUsername, err = p.ask(ctx, "  IMAP username", a.Email, true); err != nil {
		return err
	}
	if a.IMAPCommand, err = p.askCommand(ctx); err != nil {
		return err
	}

	fmt.Fprintln(out)
	fmt.Fprintln(out, "The account is created read-only. Sending is opt-in and is never")
	fmt.Fprintln(out, "enabled by default.")
	if a.EnableSend, err = p.askYesNo(ctx, "Enable sending (SMTP)?", false); err != nil {
		return err
	}
	if a.EnableSend {
		fmt.Fprintln(out)
		fmt.Fprintln(out, "Outgoing mail (SMTP), always over verified TLS")
		if a.SMTPHost, err = p.ask(ctx, "  SMTP host", "", true); err != nil {
			return err
		}
		smtpMode, modeErr := p.askChoice(ctx, "  SMTP TLS mode", []string{"STARTTLS", "implicit TLS"}, 1)
		if modeErr != nil {
			return modeErr
		}
		a.SMTPImplicitTLS = smtpMode == 1
		defaultSMTPPort := config.DefaultSMTPPort
		if a.SMTPImplicitTLS {
			defaultSMTPPort = config.DefaultSMTPPortImplicit
		}
		if a.SMTPPort, err = p.askPort(ctx, "  SMTP port", defaultSMTPPort); err != nil {
			return err
		}
		if a.SMTPUsername, err = p.ask(ctx, "  SMTP username", a.IMAPUsername, true); err != nil {
			return err
		}
		if a.SMTPCommand, err = p.askCommand(ctx); err != nil {
			return err
		}
	}

	fmt.Fprintln(out)
	if opts.Path, err = p.ask(ctx, "Configuration file", opts.Path, true); err != nil {
		return err
	}

	data, _, err := Generate(a)
	if err != nil {
		return err
	}

	written, err := writeConfig(opts.Path, data, opts.Force)
	if err != nil {
		return err
	}

	fmt.Fprintln(out)
	fmt.Fprintf(out, "Wrote %s\n", written)
	fmt.Fprintf(out, "%s\n", permissionNote())
	fmt.Fprintln(out)
	fmt.Fprintln(out, "Account summary")
	fmt.Fprintf(out, "  id:          %s\n", a.AccountID)
	fmt.Fprintf(out, "  email:       %s\n", a.Email)
	fmt.Fprintf(out, "  IMAP:        %s:%d, %s\n", a.IMAPHost, a.IMAPPort, tlsLabel(a.IMAPImplicitTLS))
	if a.EnableSend {
		fmt.Fprintf(out, "  SMTP:        %s:%d, %s\n", a.SMTPHost, a.SMTPPort, tlsLabel(a.SMTPImplicitTLS))
	} else {
		fmt.Fprintln(out, "  SMTP:        not configured (sending is disabled)")
	}
	fmt.Fprintf(out, "  credentials: IMAP %s\n", commandLabel(a.IMAPCommand))
	if a.EnableSend {
		fmt.Fprintf(out, "  credentials: SMTP %s\n", commandLabel(a.SMTPCommand))
	}
	if a.EnableSend {
		fmt.Fprintln(out, "  permissions: read, send")
	} else {
		fmt.Fprintln(out, "  permissions: read")
	}
	fmt.Fprintln(out)
	fmt.Fprintln(out, "Credential commands are shown by their executable name only; their")
	fmt.Fprintln(out, "arguments can name where the secret lives and are not printed.")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "Next steps")
	fmt.Fprintf(out, "  1. Review %s\n", written)
	fmt.Fprintf(out, "  2. Validate it:      themailroom doctor -config %s\n", written)
	fmt.Fprintf(out, "  3. Test connectivity: themailroom doctor -config %s -network\n", written)
	fmt.Fprintf(out, "  4. Start the server:  themailroom -config %s\n", written)
	fmt.Fprintln(out)

	if opts.Check == nil {
		return nil
	}
	run, err := p.askYesNo(ctx, "Run the connectivity check now? It runs the credential command and opens network connections.", false)
	if err != nil {
		return err
	}
	if !run {
		return nil
	}
	return opts.Check(ctx, written, out)
}

// tlsLabel renders the transport security of an endpoint.
func tlsLabel(implicit bool) string {
	if implicit {
		return "implicit TLS"
	}
	return "mandatory STARTTLS"
}

// commandLabel renders a credential command by its executable name only.
//
// The arguments are never printed: they can name where the secret lives.
func commandLabel(command []string) string {
	if len(command) == 0 {
		return "(none)"
	}
	return filepath.Base(command[0]) + " (arguments not shown)"
}

// permissionNote describes what the platform actually guarantees about the
// written file.
//
// POSIX mode bits are an access control mechanism; on Windows they are not
// an ACL, and Go cannot set one. Saying so plainly is the honest option:
// the alternative would be to claim a protection that does not exist.
func permissionNote() string { return permissionNoteFor(runtime.GOOS) }

// permissionNoteFor renders the note for a specific platform. It exists so
// both branches are testable on one machine.
func permissionNoteFor(goos string) string {
	if goos == "windows" {
		return "Note: on Windows the file inherits the access control list of its directory. " +
			"POSIX mode bits are not an ACL and do not restrict access here. " +
			"Restrict the file with icacls if the directory is shared."
	}
	return "The file was created with mode 0600: readable and writable by its owner only."
}
