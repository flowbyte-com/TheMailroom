package doctor

import (
	"errors"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

// quotedRun matches a backtick-, double- or single-quoted run, including
// escaped characters inside a double-quoted run.
//
// The YAML parser quotes an offending scalar in backticks, and the loader's
// validation errors quote a value with %q. Removing the quoted run removes
// the echoed value without needing to know what the value is.
var quotedRun = regexp.MustCompile("`[^`]*`" + `|"(?:\\.|[^"\\])*"` + `|'(?:''|[^'])*'`)

// absolutePath matches an absolute filesystem path inside an error message.
// Loader errors about mailbox_root or attachment_send_paths embed the path
// unquoted.
var absolutePath = regexp.MustCompile(`(^|[\s:=(,])(/[^\s:="',)]+)`)

// linePattern extracts the line reference from a YAML error. A line number
// is a safe fact to report.
var linePattern = regexp.MustCompile(`lines? ([0-9]+(?:-[0-9]+)?)`)

// credentialScalars returns the values of the credential fields in a YAML
// document.
//
// The document is walked as a YAML node tree rather than matched line by
// line, so anchors and aliases, quoted and escaped scalars, and block and
// flow collections are all resolved by the parser. The values are read only
// to be removed from an error message; they are never printed.
func credentialScalars(data []byte) []string {
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil
	}
	var out []string
	collectCredentialScalars(&doc, false, &out)
	return out
}

func collectCredentialScalars(n *yaml.Node, credential bool, out *[]string) {
	if n == nil {
		return
	}
	switch n.Kind {
	case yaml.DocumentNode, yaml.SequenceNode:
		for _, c := range n.Content {
			collectCredentialScalars(c, credential, out)
		}
	case yaml.MappingNode:
		for i := 0; i+1 < len(n.Content); i += 2 {
			key, value := n.Content[i], n.Content[i+1]
			child := credential || key.Value == "password" || key.Value == "password_command"
			collectCredentialScalars(value, child, out)
		}
	case yaml.AliasNode:
		collectCredentialScalars(n.Alias, credential, out)
	case yaml.ScalarNode:
		if credential && n.Value != "" {
			*out = append(*out, n.Value)
		}
	}
}

// describeConfigError renders a configuration failure without echoing any
// configured value.
//
// It is fail-closed by construction rather than by pattern matching:
//
//   - A YAML syntax, type or unknown-field error quotes the document, so it
//     is replaced by a fixed description and, when the parser reported one,
//     a line number. The offending content is never printed.
//   - A validation error is generated by the loader's own code, so its
//     field path and explanation are kept, but every quoted run, every
//     absolute path and every credential value is removed.
//
// Only the loader's own error text reaches this function, and only the
// fixed description or the sanitised validation message leaves it.
func describeConfigError(err error, data []byte) string {
	if err == nil {
		return ""
	}

	// A syntax error means the document cannot be trusted at all.
	var probe yaml.Node
	if yamlErr := yaml.Unmarshal(data, &probe); yamlErr != nil {
		return "the configuration is not valid YAML" + lineSuffix(yamlErr.Error()) +
			"; the file content is not printed"
	}

	// A type or unknown-field error quotes the offending scalar or names a
	// field. Neither is printed.
	var typeErr *yaml.TypeError
	if errors.As(err, &typeErr) {
		return "the configuration does not match the schema" + lineSuffix(typeErr.Error()) +
			"; the offending value is not printed"
	}

	// The duplicate-key scan reports the key it found. The key is not
	// printed, because a YAML key is document content.
	if strings.Contains(err.Error(), "duplicate key") {
		return "the configuration contains a duplicate key" + lineSuffix(err.Error()) +
			"; the key is not printed"
	}

	return sanitiseMessage(err.Error(), data)
}

// sanitiseMessage removes every configured value from a loader message.
func sanitiseMessage(msg string, data []byte) string {
	msg = quotedRun.ReplaceAllString(msg, "***")
	msg = absolutePath.ReplaceAllString(msg, "${1}***")
	for _, value := range credentialScalars(data) {
		msg = redactValue(msg, value)
	}
	return msg
}

// redactValue removes one credential value from a message.
//
// A value of three characters or more is removed wherever it appears. A
// shorter value is removed only as a whole token, because replacing every
// occurrence of a one-character secret would destroy the message without
// making it any safer.
func redactValue(msg, value string) string {
	if value == "" {
		return msg
	}
	if len(value) >= 3 {
		return strings.ReplaceAll(msg, value, "***")
	}
	token := regexp.MustCompile(`(^|[^A-Za-z0-9])` + regexp.QuoteMeta(value) + `([^A-Za-z0-9]|$)`)
	for {
		next := token.ReplaceAllString(msg, "${1}***${2}")
		if next == msg {
			return msg
		}
		msg = next
	}
}

// lineSuffix renders a YAML error's line reference, if it has one.
func lineSuffix(msg string) string {
	m := linePattern.FindStringSubmatch(msg)
	if m == nil {
		return ""
	}
	return " (line " + m[1] + ")"
}
